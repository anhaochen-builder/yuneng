# ================================================================
# 知识图谱服务
# ================================================================

class KnowledgeGraphService:
    """电力领域知识图谱服务"""

    @staticmethod
    def extract_entities(text: str) -> dict:
        entities: dict[str, Any] = {"device_type": None, "device_id": None, "fault_keywords": []}

        for keyword, dtype in DEVICE_TYPE_MAP.items():
            if keyword.lower() in text.lower():
                entities["device_type"] = dtype
                break

        match = re.search(r"[A-Z]{2,4}\d{3,4}", text)
        if match:
            entities["device_id"] = match.group()

        fault_kw_list = [
            "通讯中断", "温度过高", "振动超标", "电压异常", "电流异常",
            "功率下降", "绝缘降低", "接地故障", "并网异常", "效率降低",
            "过热", "过温", "短路", "过载", "泄漏", "SF6气压低", "局放",
            "拒动", "误动", "跳闸", "保护动作",
        ]
        for kw in fault_kw_list:
            if kw in text:
                entities["fault_keywords"].append(kw)

        return entities

    @staticmethod
    def build_graph_context(query: str) -> str:
        entities = KnowledgeGraphService.extract_entities(query)
        device_type = entities.get("device_type")
        if not device_type:
            return ""

        # 支持模糊匹配
        matched_type = None
        if device_type in KNOWLEDGE_GRAPH:
            matched_type = device_type
        else:
            for k in KNOWLEDGE_GRAPH:
                if k in device_type or device_type in k:
                    matched_type = k
                    break

        if not matched_type:
            return ""

        graph = KNOWLEDGE_GRAPH[matched_type]
        parts = [f"## {matched_type} 知识图谱扩展"]

        if entities["fault_keywords"]:
            parts.append(f"相关故障: {', '.join(entities['fault_keywords'])}")

        parts.append(f"\n常见告警类型: {', '.join(graph['alarms'])}")
        parts.append(f"常见原因: {', '.join(graph['causes'])}")
        parts.append(f"推荐排查步骤: {', '.join(graph['steps'])}")
        parts.append(f"安全注意事项: {', '.join(graph['safety'])}")

        return "\n".join(parts)


kg_service = KnowledgeGraphService()
